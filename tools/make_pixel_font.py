def rows(spec):
    return spec.split() if isinstance(spec, str) else spec

ACUTE = ["...#.", "..#.."]
GRAVE = [".#...", "..#.."]
CIRC = ["..#..", ".#.#."]
DIAER = [".....", ".#.#."]
TILDE = [".#.#.", "#.#.."]

def lower_with(base, accent):
    r = rows(G[base])[:]
    if base == 'i':
        r[0] = "....."
    r[0], r[1] = accent
    return r

for ch, base, acc in [('é','e',ACUTE),('è','e',GRAVE),('ê','e',CIRC),('ë','e',DIAER),
                      ('à','a',GRAVE),('â','a',CIRC),('ä','a',DIAER),
                      ('ù','u',GRAVE),('û','u',CIRC),('ü','u',DIAER),
                      ('î','i',CIRC),('ï','i',DIAER),('ô','o',CIRC),('ö','o',DIAER),('ñ','n',TILDE)]:
    G[ch] = lower_with(base, acc)
G['ç'] = rows(G['c']) + ["..#..", ".##.."]
G['Ç'] = rows(G['C']) + ["..#..", ".##.."]
# Uppercase accents sit above the cap height (rows -2, -1).
UPPER = {}
for ch, base, acc in [('É','E',ACUTE),('È','E',GRAVE),('Ê','E',CIRC),('À','A',GRAVE),('Â','A',CIRC),
                      ('Ô','O',CIRC),('Î','I',CIRC),('Ù','U',GRAVE),('Û','U',CIRC)]:
    UPPER[ch] = (acc, rows(G[base]))
G['œ'] = "..... ..... .#.#. #.#.# #.### #.#.. .#.##"
G['Œ'] = ".#### #.#.. #.#.. #.### #.#.. #.#.. .####"

def square(pen, x, y):
    pen.moveTo((x, y)); pen.lineTo((x, y + P)); pen.lineTo((x + P, y + P)); pen.lineTo((x + P, y)); pen.closePath()

def glyph_from(top_rows, start_row=0):
    pen = TTGlyphPen(None)
    any_pixel = False
    for i, row in enumerate(top_rows):
        r = start_row + i
        y = (6 - r) * P
        for c, bit in enumerate(row):
            if bit == '#':
                square(pen, c * P + 50, y)
                any_pixel = True
    if not any_pixel:
        pen.moveTo((0, 0)); pen.closePath()
    return pen.glyph()

order = ['.notdef']
cmap = {}
glyphs = {}
metrics = {}
glyphs['.notdef'] = glyph_from(["#####", "#...#", "#...#", "#...#", "#...#", "#...#", "#####"])
metrics['.notdef'] = (ADV, 0)
def add(ch, glyph):
    name = 'uni%04X' % ord(ch)
    order.append(name); cmap[ord(ch)] = name; glyphs[name] = glyph; metrics[name] = (ADV, 0)
for ch, spec in G.items():
    add(ch, glyph_from(rows(spec)))
for ch, (acc, base) in UPPER.items():
    add(ch, glyph_from(acc + base, start_row=-2))
add(' ', glyph_from([]))

fb = FontBuilder(1100, isTTF=True)
fb.setupGlyphOrder(order)
fb.setupCharacterMap(cmap)
fb.setupGlyf(glyphs)
fb.setupHorizontalMetrics(metrics)
fb.setupHorizontalHeader(ascent=900, descent=-200)
fb.setupNameTable({"familyName": "PolyPixel", "styleName": "Regular"})
fb.setupOS2(sTypoAscender=900, sTypoDescender=-200, usWinAscent=900, usWinDescent=200)
fb.setupPost()
fb.save("assets/fonts/PolyPixel.ttf")
print(len(order), "glyphs")
